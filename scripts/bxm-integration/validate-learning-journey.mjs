import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';

const base = process.env.FLOW_BASE_URL || 'http://127.0.0.1:4173';
const browser = await chromium.launch({ headless: true, executablePath: process.env.FLOW_CHROME_PATH });
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const page = await context.newPage();
page.setDefaultTimeout(15000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const path = '/#/programas/bxm/matematicas?convocatoria=2026-c2&pantalla=aprendizaje';
const key = 'bxm/matematica/02-2026/geometry/A1.2';
const journal = () => page.evaluate(() => JSON.parse(localStorage.getItem('bxm-mvp-progress:v1:learning:guest')));
const option = letter => page.locator(`button[data-option="${letter}"]`);
const startPrepared = () => page.getByRole('dialog', { name: 'Antes de comenzar la actividad' }).getByRole('button', { name: /Comenzar actividad|Aceptar actividad limitada/ }).click();
const results = () => page.getByRole('heading', { name: 'Tu resultado', exact: true });
const checks = [];
await mkdir('artifacts/bxm-integration', { recursive: true });
try {
  await page.goto(base + path);
  await page.getByRole('button', { name: 'Hacer diagnóstico', exact: true }).click();
  await startPrepared();
  await option('A').click();
  assert.equal(await option('A').getAttribute('aria-label'), null);
  assert.match(await option('A').innerText(), /A/);
  await page.getByRole('button', { name: 'Marcar para revisión', exact: true }).click();
  const first = await journal();
  assert.equal(first.active.items.length, 20);
  await page.reload();
  await option('A').waitFor();
  assert.equal(await option('A').getAttribute('aria-pressed'), 'true');
  assert.equal((await journal()).active.deadline, first.active.deadline);
  await page.getByRole('button', { name: 'Desmarcar', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Entregar examen', exact: true }).click();
  await results().waitFor();
  const diagnosticUrl = page.url();
  await page.reload();
  await results().waitFor();
  assert.equal(page.url(), diagnosticUrl);
  assert.equal((await journal()).results.length, 1);
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('bxm-mvp-progress:v1:events')).length), 1);
  checks.push('Free 20-item diagnostic retains answer, review flag, deadline and result across reloads');

  await page.goto(base + path + '&seccion=temario&evidencia=' + encodeURIComponent(key));
  await page.getByRole('heading', { name: 'Ecuación Canónica y Elementos de la Circunferencia', exact: true }).waitFor();
  assert((await page.locator('.katex').count()) > 0);
  await page.goto(base + path + '&seccion=practice');
  await page.getByRole('button', { name: 'Preparar práctica', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  assert.equal(await page.getByRole('button', { name: /Modo pruebas|Simular acceso/ }).count(), 0);
  assert.equal((await journal()).active, undefined);
  checks.push('Free sample lesson renders real mathematics; practice gate has no production upgrade bypass');

  // Test fixture only: the production application never grants Pro through this UI.
  await page.evaluate(() => localStorage.setItem('mep_ea_subscription_tier', 'premium'));
  await page.reload();
  await page.getByLabel('Habilidad', { exact: true }).selectOption(key);
  await page.getByRole('button', { name: 'Preparar práctica', exact: true }).click();
  await startPrepared();
  await option('A').waitFor();
  const correct = (await journal()).active.items[0].correctAnswer;
  await option(correct === 'A' ? 'B' : 'A').click();
  await page.getByRole('button', { name: 'Verificar respuesta', exact: true }).click();
  await page.getByText(/Respuesta incorrecta/).first().waitFor();
  await option(correct).click();
  await page.getByRole('button', { name: 'Verificar respuesta', exact: true }).click();
  const activeUrl = page.url();
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Reanudar aprendizaje', exact: true }).click();
  await option('A').waitFor();
  const saved = await journal();
  assert.equal(saved.active.states[0].firstResponse.isCorrect, false);
  assert.equal(saved.active.states[0].retryAttempts.length, 1);
  await page.evaluate(() => localStorage.setItem('mep_ea_subscription_tier', 'free'));
  await page.goto(activeUrl);
  await page.reload();
  await page.getByRole('heading', { name: 'Práctica Pro', exact: true }).waitFor();
  assert.deepEqual((await journal()).active, saved.active);
  assert.equal(await page.locator('button[data-option]').count(), 0);
  await page.evaluate(() => localStorage.setItem('mep_ea_subscription_tier', 'premium'));
  await page.reload();
  await page.getByRole('button', { name: 'Finalizar sesión', exact: true }).click();
  await results().waitFor();
  assert.equal((await journal()).results[0].firstResponseCorrectCount, 0);
  checks.push('Pro practice retries retain first-response scoring; downgrade blocks direct-link resume and preserves the snapshot');

  await page.goto(base + path + '&seccion=progress');
  await page.getByRole('heading', { name: 'Tu preparación', exact: true }).waitFor();
  await page.getByRole('button', { name: /Dominio por Evidencia/ }).click();
  assert.equal(await page.getByRole('table').count(), 1);
  await page.evaluate(() => localStorage.setItem('mep_ea_user', JSON.stringify({ id: 'isolated-profile', name: 'Perfil de prueba' })));
  await page.reload();
  await page.getByText('Aún no hay resultados de aprendizaje.', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Revisar aprendizaje', exact: true }).count(), 0);
  checks.push('Pro progress receives learning history and another profile cannot see guest results');
  const retained = await journal();
  await page.route('**/assets/HelperPage-*.js', route => route.abort());
  await page.goto(base + '/#/ayuda');
  await page.getByRole('heading', { name: 'No pudimos abrir esta página', exact: true }).waitFor();
  assert.deepEqual(await journal(), retained);
  await page.unroute('**/assets/HelperPage-*.js');
  await page.getByRole('button', { name: 'Reintentar carga', exact: true }).click();
  await page.getByRole('heading', { name: 'Guía y recursos', exact: true }).waitFor();
  assert.deepEqual(await journal(), retained);
  checks.push('Failed lazy chunk reaches the root recovery screen; retry reloads successfully and retains history');
  assert.deepEqual(errors, []);
  await writeFile('artifacts/bxm-integration/journey-results.json', JSON.stringify({ status: 'passed', checks, errors }, null, 2));
  console.log(JSON.stringify({ status: 'passed', checks }, null, 2));
} catch (error) {
  await page.screenshot({ path: 'artifacts/bxm-integration/failure.png', fullPage: true }).catch(() => {});
  await writeFile('artifacts/bxm-integration/journey-results.json', JSON.stringify({ status: 'failed', checks, errors, failure: String(error) }, null, 2));
  throw error;
} finally { await browser.close(); }
